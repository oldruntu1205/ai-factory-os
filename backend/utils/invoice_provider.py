# ============ 工厂 ============

def get_provider(provider_name: str):
    """按配置返回发票平台 Provider 实例"""
    providers = {
        PROVIDER_MOCK: MockInvoiceProvider,
        PROVIDER_BAIWANG: BaiwangProvider,
        PROVIDER_NUONUO: NuoNuoProvider,
    }
    cls = providers.get(provider_name or PROVIDER_MOCK)
    if not cls:
        raise InvoiceProviderError(f"未知发票平台: {provider_name}")
    return cls()
