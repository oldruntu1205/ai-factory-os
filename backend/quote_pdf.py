"""
quote_pdf.py —— 自动生成 PDF 报价单（第五阶段 第四部分）

使用 reportlab 生成专业报价单 PDF。
"""
import os
from datetime import datetime

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from config import BASE_DIR


def create_quote_pdf(quotation: dict, output_path: str = None) -> str:
    """生成报价单 PDF，返回文件路径"""
    if not output_path:
        pdf_dir = os.path.join(BASE_DIR, "output", "quotes")
        os.makedirs(pdf_dir, exist_ok=True)
        output_path = os.path.join(pdf_dir, f"{quotation['quotation_no']}.pdf")

    c = canvas.Canvas(output_path, pagesize=A4)
    width, height = A4

    # 公司头部
    c.setFillColor(colors.HexColor("#1a365d"))
    c.rect(0, height - 90, width, 90, fill=1, stroke=0)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 22)
    c.drawString(40, height - 45, "QUOTATION")
    c.setFont("Helvetica", 10)
    c.drawString(40, height - 65, quotation.get("company_name", "Industrial AI Platform"))

    # 报价信息
    c.setFillColor(colors.black)
    c.setFont("Helvetica-Bold", 11)
    c.drawString(40, height - 120, f"Quotation No: {quotation['quotation_no']}")
    c.setFont("Helvetica", 10)
    c.drawString(40, height - 138, f"Date: {datetime.now().strftime('%Y-%m-%d')}")
    c.drawString(40, height - 156, f"Customer: {quotation.get('customer_name', '-')}")

    # 明细表
    y = height - 210
    table_y = y
    # 表头
    c.setFillColor(colors.HexColor("#e2e8f0"))
    c.rect(40, table_y - 20, width - 80, 22, fill=1, stroke=0)
    c.setFillColor(colors.black)
    c.setFont("Helvetica-Bold", 10)
    c.drawString(50, table_y - 14, "Product")
    c.drawString(300, table_y - 14, "Quantity")
    c.drawString(380, table_y - 14, "Unit Price")
    c.drawString(470, table_y - 14, "Amount")

    row_y = table_y - 45
    c.setFont("Helvetica", 10)
    c.drawString(50, row_y, quotation.get("product", "-"))
    c.drawString(300, row_y, str(quotation.get("quantity", 0)))
    c.drawString(380, row_y, f"{quotation.get('currency', 'USD')} {quotation.get('unit_price', 0):,.2f}")
    c.drawString(470, row_y, f"{quotation.get('currency', 'USD')} {quotation.get('total_amount', 0):,.2f}")

    # 合计
    c.setStrokeColor(colors.HexColor("#cbd5e1"))
    c.line(40, row_y - 12, width - 40, row_y - 12)
    c.setFont("Helvetica-Bold", 11)
    c.drawString(380, row_y - 32, "TOTAL")
    c.drawString(470, row_y - 32, f"{quotation.get('currency', 'USD')} {quotation.get('total_amount', 0):,.2f}")

    # 条款
    c.setFont("Helvetica", 9)
    c.setFillColor(colors.grey)
    c.drawString(40, row_y - 70, f"Delivery: {quotation.get('delivery_days', 30)} days")
    c.drawString(40, row_y - 85, f"Payment: {quotation.get('payment_terms', 'T/T 30% deposit')}")
    c.drawString(40, row_y - 100, "Validity: 30 days from issue date")
    c.drawString(40, row_y - 115, "Terms: This quotation is subject to our standard terms and conditions.")

    # 页脚
    c.setFillColor(colors.HexColor("#94a3b8"))
    c.drawString(40, 40, "Generated by Industrial AI Employee Platform - AI Quotation Agent")

    c.showPage()
    c.save()
    return output_path
