const SiteLangCtx = createContext({
  lang: DEFAULT_LANG,
  setLang: () => {},
  t: (key) => key,
})

export function SiteLanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const stored = typeof localStorage !== 'undefined' ? localStorage.getItem('site_lang') : null
    return stored && DICT[stored] ? stored : DEFAULT_LANG
  })

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang
    }
  }, [lang])

  const setLang = useCallback((code) => {
    if (DICT[code]) {
      localStorage.setItem('site_lang', code)
      setLangState(code)
    }
  }, [])

  const t = useCallback((key, vars = {}) => {
    const value = DICT[lang]?.[key] ?? DICT[DEFAULT_LANG]?.[key] ?? key
    return Object.entries(vars).reduce((str, [k, v]) => str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)), value)
  }, [lang])

  return (
    <SiteLangCtx.Provider value={{ lang, setLang, t }}>
      {children}
    </SiteLangCtx.Provider>
  )
}

export const useSiteLang = () => useContext(SiteLangCtx)
